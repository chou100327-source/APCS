/* ---- 共用小工具 ---- */
/* 某一週包含哪幾天 */
function daysOfWeek(week) {
  return STUDY.days.filter(d => d.d >= week.start && d.d <= week.end);
}
/* 每一天的打勾 key。固定用日期，才不會因為好幾天指向同一份教材而連動打勾。
   （教材本身「讀完了」的標記另外用教材路徑當 key，兩種 key 不會撞。） */
function dayKey(day) { return "day:" + day.d; }
/* 距離考試天數（用真實今天日期動態計算） */
function daysToExam() {
  const exam = new Date(STUDY.exam + "T00:00:00");
  const today = new Date(); today.setHours(0, 0, 0, 0);
  return Math.round((exam - today) / 86400000);
}
/* 今天是第幾週（回傳 week.id 或 null） */
function currentWeekId() {
  const t = todayStr();
  const w = STUDY.weeks.find(w => t >= w.start && t <= w.end);
  return w ? w.id : null;
}
/* 今天的日期字串（YYYY-MM-DD），用來把「今天」那一列標亮 */
function todayStr() {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}
/* 日期 "2026-09-13" → "9/13" */
function fmtDay(s) {
  const [, m, d] = s.split("-");
  return `${Number(m)}/${d}`;
}
